-- MLOps dataset: experiment tracking, model registry, deployments and online predictions.

PRAGMA foreign_keys = ON;


CREATE TABLE experiments (
  experiment_id INTEGER PRIMARY KEY,
  name          TEXT NOT NULL UNIQUE,
  team          TEXT NOT NULL,
  owner         TEXT NOT NULL,
  task          TEXT NOT NULL,
  created_at    DATETIME NOT NULL
);
CREATE TABLE runs (
  run_id         INTEGER PRIMARY KEY,
  experiment_id  INTEGER NOT NULL REFERENCES experiments(experiment_id),
  parent_run_id  INTEGER REFERENCES runs(run_id),
  run_name       TEXT NOT NULL,
  model_type     TEXT NOT NULL,
  learning_rate  REAL,
  batch_size     INTEGER,
  status         TEXT NOT NULL CHECK (status IN ('RUNNING','FINISHED','FAILED','KILLED')),
  started_at     DATETIME NOT NULL,
  ended_at       DATETIME,
  gpu_hours      REAL,
  triggered_by   TEXT NOT NULL
);
CREATE TABLE metrics (
  run_id      INTEGER NOT NULL REFERENCES runs(run_id),
  metric_name TEXT NOT NULL,
  step        INTEGER NOT NULL,
  value       REAL NOT NULL,
  PRIMARY KEY (run_id, metric_name, step)
);
CREATE TABLE models (
  model_id      INTEGER PRIMARY KEY,
  name          TEXT NOT NULL,
  version       INTEGER NOT NULL,
  run_id        INTEGER NOT NULL REFERENCES runs(run_id),
  stage         TEXT NOT NULL CHECK (stage IN ('None','Staging','Production','Archived')),
  registered_at DATETIME NOT NULL,
  UNIQUE (name, version)
);
CREATE TABLE deployments (
  deployment_id INTEGER PRIMARY KEY,
  model_id      INTEGER NOT NULL REFERENCES models(model_id),
  environment   TEXT NOT NULL CHECK (environment IN ('staging','production','shadow')),
  deployed_at   DATETIME NOT NULL,
  retired_at    DATETIME,
  replicas      INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE predictions (
  prediction_id   INTEGER PRIMARY KEY,
  deployment_id   INTEGER NOT NULL REFERENCES deployments(deployment_id),
  predicted_at    DATETIME NOT NULL,
  predicted_label TEXT NOT NULL,
  actual_label    TEXT,
  score           REAL NOT NULL,
  latency_ms      INTEGER NOT NULL
);

