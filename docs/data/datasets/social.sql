-- Social dataset: a small social network (users, posts, likes, follows, messages, comments).

PRAGMA foreign_keys = ON;


CREATE TABLE users (
  user_id     INTEGER PRIMARY KEY,
  username    TEXT NOT NULL UNIQUE,
  full_name   TEXT NOT NULL,
  country     TEXT NOT NULL,
  joined_on   DATE NOT NULL,
  is_verified INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE posts (
  post_id    INTEGER PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  created_at DATETIME NOT NULL,
  post_type  TEXT NOT NULL CHECK (post_type IN ('text','photo','video','link')),
  topic      TEXT NOT NULL,
  char_count INTEGER NOT NULL
);
CREATE TABLE likes (
  like_id  INTEGER PRIMARY KEY,
  user_id  INTEGER NOT NULL REFERENCES users(user_id),
  post_id  INTEGER NOT NULL REFERENCES posts(post_id),
  liked_at DATETIME NOT NULL,
  UNIQUE (user_id, post_id)
);
CREATE TABLE follows (
  follower_id INTEGER NOT NULL REFERENCES users(user_id),
  followee_id INTEGER NOT NULL REFERENCES users(user_id),
  followed_at DATETIME NOT NULL,
  PRIMARY KEY (follower_id, followee_id),
  CHECK (follower_id <> followee_id)
);
CREATE TABLE messages (
  message_id  INTEGER PRIMARY KEY,
  sender_id   INTEGER NOT NULL REFERENCES users(user_id),
  receiver_id INTEGER NOT NULL REFERENCES users(user_id),
  sent_at     DATETIME NOT NULL,
  read_at     DATETIME
);
CREATE TABLE comments (
  comment_id        INTEGER PRIMARY KEY,
  post_id           INTEGER NOT NULL REFERENCES posts(post_id),
  user_id           INTEGER NOT NULL REFERENCES users(user_id),
  parent_comment_id INTEGER REFERENCES comments(comment_id),
  created_at        DATETIME NOT NULL
);

