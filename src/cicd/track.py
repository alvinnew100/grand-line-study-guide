def _m(mid, title, summary, lessons, problems=()):
    return dict(
        id=mid, title=title, summary=summary,
        lessons=[dict(id=i, title=t, file=f) for i, t, f in lessons if (_HERE / "lessons" / f).exists()],
        problems=[p for p in problems if p in _DEFINED],
    )


