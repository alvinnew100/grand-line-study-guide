-- Bank dataset: mirrors the example schema of Beaulieu, Learning SQL (Appendix A).

-- The book's `transaction` table is named `txn` here (TRANSACTION is an SQL keyword).

PRAGMA foreign_keys = ON;


CREATE TABLE department (
  dept_id   INTEGER PRIMARY KEY,
  name      VARCHAR(20) NOT NULL
);
CREATE TABLE branch (
  branch_id INTEGER PRIMARY KEY,
  name      VARCHAR(20) NOT NULL,
  address   VARCHAR(30),
  city      VARCHAR(20),
  state     CHAR(2),
  zip       VARCHAR(12)
);
CREATE TABLE employee (
  emp_id             INTEGER PRIMARY KEY,
  fname              VARCHAR(20) NOT NULL,
  lname              VARCHAR(20) NOT NULL,
  start_date         DATE NOT NULL,
  end_date           DATE,
  superior_emp_id    INTEGER REFERENCES employee(emp_id),
  dept_id            INTEGER REFERENCES department(dept_id),
  title              VARCHAR(20),
  assigned_branch_id INTEGER REFERENCES branch(branch_id)
);
CREATE TABLE product_type (
  product_type_cd VARCHAR(10) PRIMARY KEY,
  name            VARCHAR(50)
);
CREATE TABLE product (
  product_cd      VARCHAR(10) PRIMARY KEY,
  name            VARCHAR(50) NOT NULL,
  product_type_cd VARCHAR(10) REFERENCES product_type(product_type_cd),
  date_offered    DATE,
  date_retired    DATE
);
CREATE TABLE customer (
  cust_id      INTEGER PRIMARY KEY,
  fed_id       VARCHAR(12) NOT NULL UNIQUE,
  cust_type_cd CHAR(1) NOT NULL CHECK (cust_type_cd IN ('I','B')),
  address      VARCHAR(30),
  city         VARCHAR(20),
  state        VARCHAR(20),
  postal_code  VARCHAR(10)
);
CREATE TABLE individual (
  cust_id    INTEGER PRIMARY KEY REFERENCES customer(cust_id),
  fname      VARCHAR(30) NOT NULL,
  lname      VARCHAR(30) NOT NULL,
  birth_date DATE
);
CREATE TABLE business (
  cust_id     INTEGER PRIMARY KEY REFERENCES customer(cust_id),
  name        VARCHAR(40) NOT NULL,
  state_id    VARCHAR(10) NOT NULL,
  incorp_date DATE
);
CREATE TABLE officer (
  officer_id INTEGER PRIMARY KEY,
  cust_id    INTEGER NOT NULL REFERENCES business(cust_id),
  fname      VARCHAR(30) NOT NULL,
  lname      VARCHAR(30) NOT NULL,
  title      VARCHAR(20),
  start_date DATE NOT NULL,
  end_date   DATE
);
CREATE TABLE account (
  account_id         INTEGER PRIMARY KEY,
  product_cd         VARCHAR(10) NOT NULL REFERENCES product(product_cd),
  cust_id            INTEGER NOT NULL REFERENCES customer(cust_id),
  open_date          DATE NOT NULL,
  close_date         DATE,
  last_activity_date DATE,
  status             VARCHAR(10) CHECK (status IN ('ACTIVE','CLOSED','FROZEN')),
  open_branch_id     INTEGER REFERENCES branch(branch_id),
  open_emp_id        INTEGER REFERENCES employee(emp_id),
  avail_balance      NUMERIC(10,2),
  pending_balance    NUMERIC(10,2)
);
CREATE TABLE txn (
  txn_id              INTEGER PRIMARY KEY,
  txn_date            DATETIME NOT NULL,
  account_id          INTEGER NOT NULL REFERENCES account(account_id),
  txn_type_cd         VARCHAR(10) CHECK (txn_type_cd IN ('DBT','CDT')),
  amount              NUMERIC(10,2) NOT NULL,
  teller_emp_id       INTEGER REFERENCES employee(emp_id),
  execution_branch_id INTEGER REFERENCES branch(branch_id),
  funds_avail_date    DATETIME
);

