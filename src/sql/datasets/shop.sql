-- Shop dataset: a small e-commerce store (customers, catalogue, orders, web events).

PRAGMA foreign_keys = ON;


CREATE TABLE categories (
  category_id INTEGER PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE,
  parent_id   INTEGER REFERENCES categories(category_id)
);
CREATE TABLE products (
  product_id   INTEGER PRIMARY KEY,
  name         TEXT NOT NULL,
  category_id  INTEGER NOT NULL REFERENCES categories(category_id),
  price        REAL NOT NULL CHECK (price > 0),
  cost         REAL NOT NULL,
  launched_on  DATE NOT NULL,
  discontinued INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE customers (
  customer_id  INTEGER PRIMARY KEY,
  first_name   TEXT NOT NULL,
  last_name    TEXT NOT NULL,
  email        TEXT UNIQUE,
  city         TEXT,
  country      TEXT NOT NULL,
  signup_date  DATE NOT NULL,
  referred_by  INTEGER REFERENCES customers(customer_id)
);
CREATE TABLE orders (
  order_id     INTEGER PRIMARY KEY,
  customer_id  INTEGER NOT NULL REFERENCES customers(customer_id),
  order_date   DATE NOT NULL,
  status       TEXT NOT NULL CHECK (status IN ('pending','shipped','delivered','cancelled','returned')),
  shipping_fee REAL NOT NULL DEFAULT 0
);
CREATE TABLE order_items (
  order_item_id INTEGER PRIMARY KEY,
  order_id      INTEGER NOT NULL REFERENCES orders(order_id),
  product_id    INTEGER NOT NULL REFERENCES products(product_id),
  quantity      INTEGER NOT NULL CHECK (quantity > 0),
  unit_price    REAL NOT NULL,
  discount      REAL NOT NULL DEFAULT 0
);
CREATE TABLE web_events (
  event_id    INTEGER PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
  event_time  DATETIME NOT NULL,
  event_type  TEXT NOT NULL,
  page        TEXT
);
CREATE TABLE logins (
  customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
  login_date  DATE NOT NULL,
  PRIMARY KEY (customer_id, login_date)
);
CREATE TABLE customer_imports (
  import_id   INTEGER PRIMARY KEY,
  email       TEXT NOT NULL,
  full_name   TEXT NOT NULL,
  source      TEXT NOT NULL,
  imported_at DATETIME NOT NULL
);

